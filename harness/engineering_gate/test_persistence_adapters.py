class AdapterFixtures(test_flyway.FlywayFixtures):
    def setUp(self):
        super().setUp()
        import calibrate_persistence

        self.persistence = calibrate_persistence
        self.persistence_tools = os.environ.get("DOMAIN_FORGE_GATE_PERSISTENCE_TOOLS", "")
        self.assertTrue(self.persistence_tools, "必须提供实际持久化工具，不跳过")
        self.contract = self.root / "adapters.json"
        self.private = self.root / "connections.json"
        self.new_databases()
        self.application()

    def new_databases(self):
        self.peers = {"master": dict(self.credentials)}
        self.start_database()
        self.peers["inventory"] = dict(self.credentials)
        self.private.write_text(json.dumps({"schema": 1, "databases": self.peers}), encoding="utf-8")
        self.private.chmod(0o600)

    def application(self):
        pom = self.project / "pom.xml"
        text = pom.read_text(encoding="utf-8")
        pom.write_text(text[:text.index("<dependencyManagement>")] + self.persistence.framework_pom() + text[text.index("<build>"):], encoding="utf-8")
        self.write("src/test-named-production/java/probe/adapter/PersistenceAdapterFixture.java", (HERE / "PersistenceAdapterFixture.java").read_text(encoding="utf-8"))
        for name in ("PersistenceRowMapper.xml", "PersistenceBatchMapper.xml"):
            self.write("src/main/resources/mapper/" + name, (HERE / name).read_text(encoding="utf-8"))
        properties = "spring.flyway.enabled=false\nmybatis-plus.global-config.banner=false\nspring.datasource.dynamic.primary=master\nspring.datasource.dynamic.strict=true\nspring.sql.init.mode=never\n"
        for alias in self.peers:
            for key, suffix in (("url", "URL"), ("username", "USER"), ("password", "PASSWORD")):
                properties += "spring.datasource.dynamic.datasource." + alias + "." + key + "=${DF_GATE_" + alias.upper() + "_" + suffix + "}\n"
            properties += "spring.datasource.dynamic.datasource." + alias + ".hikari.connection-init-sql=SET TIME ZONE 'Asia/Shanghai'\n"
        self.write("src/main/resources/application.properties", properties)
        self.definition = {"schema": 1, "application": "probe.adapter.PersistenceAdapterFixture", "bean": "adapter", "factory": "sqlSessionFactory", "datasource": "dataSource", "manager": "transactionManager", "profile": "mapping"}

    def seed(self, profile):
        self.definition["profile"] = profile
        for alias in self.peers:
            self.sql(alias, SCHEMA)
        if profile == "pagination":
            self.sql("master", "INSERT INTO gate_adapter(id,tenant,quantity,revision) VALUES (1,'A',1,0),(2,'A',2,0),(3,'A',3,0),(4,'B',4,0),(5,'B',5,0); INSERT INTO gate_detail VALUES(1,1),(2,1),(3,2),(4,4);")
        elif profile == "concurrency":
            self.sql("master", "INSERT INTO gate_adapter(id,tenant,quantity,revision) VALUES(1,'A',100,0);")

    def sql(self, alias, sql):
        return self.docker("exec", self.peers[alias]["container"], "psql", "-U", "gate", "-d", "gate", "-v", "ON_ERROR_STOP=1", "-At", "-c", sql)

    def replace(self, old, new):
        path = self.project / "src/test-named-production/java/probe/adapter/PersistenceAdapterFixture.java"
        text = path.read_text(encoding="utf-8")
        self.assertIn(old, text)
        path.write_text(text.replace(old, new), encoding="utf-8")

    def replace_sql(self, old, new):
        path = self.project / "src/main/resources/mapper/PersistenceRowMapper.xml"
        text = path.read_text(encoding="utf-8")
        self.assertIn(old, text)
        import html
        path.write_text(text.replace(old, html.escape(new, quote=False)), encoding="utf-8")

    def command(self, diagnostic=None):
        self.contract.write_text(json.dumps(self.definition), encoding="utf-8")
        result = subprocess.run([sys.executable, "-B", str(ENTRY), "--project", str(self.project), "--adapters", str(self.contract), "--connections", str(self.private),
                                 "--persistence-tools", self.persistence_tools, "--migration-tools", self.tools, "--maven-home", self.maven, "--repository", self.repository],
                                capture_output=True, text=True, timeout=40)
        self.assertTrue(result.stdout.strip(), "具体适配入口未提供声明行为：" + result.stderr)
        report = json.loads(result.stdout)
        detail = json.dumps({key: report.get(key) for key in ("ok", "diagnostics", "native_observation")}, ensure_ascii=False)
        for name in ("adapter-observer-compile.log", "adapter-runtime.log", "maven-scope.log"):
            path = self.project / "target" / name
            if path.is_file():
                detail += "\n" + path.read_text(encoding="utf-8")[-1500:]
        self.assertEqual(result.returncode, 0 if diagnostic is None else 1, detail)
        if diagnostic:
            self.assertIn(diagnostic, [item["code"] for item in report["diagnostics"]], detail)
        for value in self.peers.values():
            self.assertNotIn(value["password"], json.dumps(report))
        return report

    def repair(self, profile):
        self.repair_count += 1
        self.project = self.root / ("adapter-repaired-" + str(self.repair_count))
        self.fixture()
        self.start_database()
        self.new_databases()
        self.application()
        self.seed(profile)


