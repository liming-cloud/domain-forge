class AdapterMigrationFixtures(AdapterFixtures):
    def migration_application(self, phase):
        if phase != "initialize":
            self.repair_count += 1
            self.project = self.root / ("migration-phase-" + str(self.repair_count))
            self.fixture()
            self.application()
        self.definition.update(profile="migration", phase=phase, migrations={})
        self.write("src/test-named-production/java/probe/adapter/PersistenceMigrationFixture.java", (HERE / "PersistenceMigrationFixture.java").read_text(encoding="utf-8"))
        for alias in self.peers:
            init = "CREATE TABLE gate_marker(id INTEGER PRIMARY KEY,label TEXT NOT NULL); INSERT INTO gate_marker VALUES(1,'" + alias + ":v1');"
            scripts = [init]
            if phase in {"upgrade", "failure", "recovery"}:
                scripts.append("ALTER TABLE gate_marker ADD COLUMN generation INTEGER NOT NULL DEFAULT 2; UPDATE gate_marker SET label='" + alias + ":v2' WHERE id=1;")
                if phase == "failure" and alias == "inventory":
                    scripts[1] += "ALTER TABLE gate_marker ADD CONSTRAINT deliberate_failure CHECK(id<0);"
            self.definition["migrations"][alias] = []
            for index, sql in enumerate(scripts, 1):
                resource = "db/" + alias + "/V" + str(index) + ("__init.sql" if index == 1 else "__upgrade.sql")
                path = self.write("src/main/resources/" + resource, sql)
                self.definition["migrations"][alias].append({"resource": resource, "sha256": hashlib.sha256(path.read_bytes()).hexdigest()})

    def preserve_existing_rows(self):
        for alias in self.peers:
            self.sql(alias, "INSERT INTO gate_marker VALUES(99,'retained');")


