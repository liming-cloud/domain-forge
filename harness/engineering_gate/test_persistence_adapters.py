class AdapterPartitionChecks(unittest.TestCase):
    def test_adapters_are_registered_once_with_native_environment_and_ci(self):
        catalog = json.loads((HERE.parent / "control_plane/catalog.json").read_text(encoding="utf-8"))
        workflow = (HERE.parents[1] / ".github/workflows/control-plane.yml").read_text(encoding="utf-8")
        loader, module = unittest.TestLoader(), sys.modules[__name__]
        def identifiers(suite):
            if isinstance(suite, unittest.TestCase):
                return [suite.id()]
            return [name for child in suite for name in identifiers(child)]
        complete = identifiers(loader.loadTestsFromModule(module))
        self.assertEqual(len(complete), len(set(complete)), "具体适配模块不得重复加载用例")
        selected = set()
        for check, names in (
                ("persistence-gate", ["AdapterCompositionCommands"]),
                ("persistence-mapping-tests", ["AdapterMappingCommands"]),
                ("persistence-pagination-tests", ["AdapterPaginationCommands"]),
                ("persistence-pagination-plugin-tests", ["AdapterPaginationPluginCommands"]),
                ("persistence-concurrency-tests", ["AdapterConcurrencyCommands"]),
                ("persistence-condition-tests", ["AdapterConcurrencyConditionCommands"]),
                ("persistence-affected-rows-tests", ["AdapterAffectedRowsCommands"]),
                ("persistence-batch-tests", ["AdapterBatchCommands"]),
                ("persistence-migration-tests", ["AdapterMigrationCommands"]),
                ("persistence-migration-recovery-tests", ["AdapterMigrationRecoveryCommands"]),
                ("persistence-migration-rejection-tests", ["AdapterMigrationRejectionCommands"]),
                ("persistence-adapter-integrity-tests", ["AdapterIntegrityCommands"]),
                ("persistence-migration-provenance-tests", ["AdapterMigrationProvenanceCommands"]),
                ("persistence-migration-failure-source-tests", ["AdapterMigrationFailureSourceCommands"]),
                ("persistence-adapter-input-tests", ["AdapterInputChecks", "AdapterToolQualityChecks", "AdapterPartitionChecks"])):
            self.assertIn(check, catalog["checks"], "具体适配分组未登记")
            definition = catalog["checks"][check]
            argv = ["@python", "-B", "harness/engineering_gate/test_persistence_adapters.py", *names]
            self.assertEqual(definition["argv"], argv, "具体适配命令偏离登记")
            self.assertEqual(definition["environment_argv"], ["@python", "-B", "harness/engineering_gate/calibrate_persistence.py", "--environment"], "具体适配环境入口偏离")
            self.assertTrue(definition["requires_test_count"])
            self.assertIn(check, catalog["maintenance"]["checks"])
            self.assertEqual(workflow.splitlines().count("        run: python " + " ".join(argv[1:])), 1, "具体适配 CI 入口缺失或重复")
            group = identifiers(loader.loadTestsFromNames(names, module))
            self.assertTrue(group)
            self.assertEqual(len(group), len(set(group)), "具体适配分组内用例重复")
            self.assertFalse(selected & set(group), "具体适配跨组用例重复")
            selected.update(group)
        self.assertEqual(selected, set(complete), "具体适配分组遗漏用例")


